"""Generate app/flexgap-fallback.css: margin-based spacing for engines without flexbox `gap`.

Tizen 5.0 TVs (2019 models such as the Q70R) ship a Chromium that predates flexbox
gap (Chrome 84). index.html adds `no-flexgap` to <html> on such engines, which turns
these rules on. Regenerate after changing a `gap` in style.css.
"""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
source = re.sub(r'/\*.*?\*/', '', (root / 'app/style.css').read_text(), flags=re.S)
target = root / 'app/flexgap-fallback.css'

# Containers whose flex-direction comes from a different rule than their gap.
DIRECTION = {
    '.l-list .quiet-utils.is-text': 'column',
    '.l-list .quiet-utils .u[data-action="util.settings"] .u-content': 'row-reverse',
    '.l-list .quiet-utils.is-text .u-content': 'row-reverse',
}
SIDE = {'row': 'left', 'column': 'top', 'row-reverse': 'right'}

rules = []
for selectors, body in re.findall(r'([^{}@]+)\{([^{}]*)\}', re.sub(r'@media[^{]*\{|@keyframes[^{]*\{(?:[^{}]*\{[^{}]*\})*[^{}]*\}', '', source)):
    gap = re.search(r'(?:^|;)gap:([^;]+)', body)
    if not gap:
        continue
    direction = re.search(r'flex-direction:([a-z-]+)', body)
    for selector in selectors.split(','):
        selector = selector.strip()
        rules.append((selector, DIRECTION.get(selector, direction.group(1) if direction else 'row'), gap.group(1).strip()))

# A container that matches gap rules in different directions must clear the other sides,
# otherwise a lower-priority rule's margin would survive.
families = {}
for selector, direction, _ in rules:
    families.setdefault(selector.split()[-1].split('.')[1].split('[')[0], set()).add(direction)

lines = ['/* Generated by scripts/flexgap-fallback.py from style.css. Do not edit by hand. */']
for selector, direction, gap in rules:
    decls = ['margin-' + SIDE[direction] + ':' + gap]
    if len(families[selector.split()[-1].split('.')[1].split('[')[0]]) > 1:
        decls += ['margin-' + side + ':0' for d, side in SIDE.items() if d != direction]
    lines.append('.no-flexgap ' + selector + '>*+*{' + ';'.join(decls) + '}')
# Children that push themselves aside with an auto margin keep it.
for selectors, body in re.findall(r'([^{}@]+)\{([^{}]*)\}', source):
    for side in re.findall(r'margin-(left|right):auto', body):
        lines.append(','.join('.no-flexgap ' + sel.strip() for sel in selectors.split(',')) + '{margin-' + side + ':auto!important}')
# Children that add their own margin on top of the container gap.
lines.append('.no-flexgap .setting-options>.setting-choice.setting-retry{margin-top:20px}')
# Text-only controls hide the icon before the label; gap ignores hidden items, margins don't.
lines.append('.no-flexgap .quiet-utils.is-text .u-content>*{margin:0!important}')
target.write_text('\n'.join(lines) + '\n')
print('Wrote ' + str(len(rules)) + ' fallback rules to ' + str(target.relative_to(root)))
